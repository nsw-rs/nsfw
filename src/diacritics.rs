pub fn remove(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match MAP.binary_search_by_key(&c, |e| e.0) {
            Ok(i) => out.push_str(MAP[i].1),
            Err(_) => out.push(c),
        }
    }
    out
}
